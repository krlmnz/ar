#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════
// APP CONFIG — writes tools-apps/map-atelier/js/config.js from the
// same token source the rest of the site uses (_data/mapbox.js).
//
// The app hardcodes its credentials in a module rather than reading
// the build's data cascade — it is a standalone ES-module app, not a
// Nunjucks page. That left config.js gitignored and therefore absent
// on Netlify, where ten modules import it: the graph failed at import
// and the editor rendered an empty shell. Generating the file at build
// time keeps the token out of git and out of the deploy log while
// making the app boot anywhere the site builds.
//
// Idempotent, and safe to run with no token at all: the app then loads
// with a dead canvas, the same failure mode _data/mapbox.js chooses for
// map pages, rather than a build error.
// ═══════════════════════════════════════════════════════════════
const fs = require('fs');
const path = require('path');

const mapbox = require('../_data/mapbox.js');

const APP_DIR = path.join(__dirname, '..', 'tools-apps', 'map-atelier', 'js');
const EXAMPLE = path.join(APP_DIR, 'config.example.js');
const TARGET = path.join(APP_DIR, 'config.js');

const example = fs.readFileSync(EXAMPLE, 'utf8');

// Swap only the two lines that carry credentials. Everything else in the
// example — DEFAULT_CENTER, the three page filenames — is real config that
// the app depends on, so it is copied through untouched rather than
// re-declared here where it would quietly drift.
const generated = example
  .replace(
    /^export const MAPBOX_TOKEN = .*$/m,
    `export const MAPBOX_TOKEN = ${JSON.stringify(mapbox.token || '')};`
  )
  .replace(
    /^export const MAP_STYLE = .*$/m,
    `export const MAP_STYLE = ${JSON.stringify(mapbox.style)};`
  )
  .replace(
    /^\/\/ Copy this file to config\.js[\s\S]*?_data\/mapbox\.js\.$/m,
    '// GENERATED by scripts/build-app-config.js — do not edit.\n' +
    '// Change the token via MAPBOX_TOKEN or _data/mapbox.local.json;\n' +
    '// change anything else in config.example.js.'
  );

fs.writeFileSync(TARGET, generated);

if (!mapbox.token) {
  console.warn('[andean-road] No Mapbox token — the Atelier will load without a map.');
} else {
  console.log('[andean-road] Wrote tools-apps/map-atelier/js/config.js');
}
